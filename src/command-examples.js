export function commandExamples(line) {
  if (line.startsWith('/crew add NAME --role')) return [line, '  Example: /crew add frontend --role frontend-dev', ''];
  if (line.startsWith('/crew role NAME --role'))
    return [line, '  Example: /crew role frontend --role frontend-dev', ''];
  const entry = Object.entries(COMMAND_EXAMPLES).find(([prefix]) => line.startsWith(prefix));
  return entry ? [line, `  Example: ${entry[1]}`, ''] : [line];
}
